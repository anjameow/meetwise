#!/usr/bin/env bash
# Builds single-file copies of each edge function (shared code inlined) into
# supabase/dashboard/, for people who deploy by pasting into the Supabase
# dashboard editor instead of using the Supabase CLI.
set -euo pipefail
cd "$(dirname "$0")/.."
mkdir -p supabase/dashboard
for f in run-matching generate-recommendations scheduler resume-url delete-account; do
  npx esbuild "supabase/functions/$f/index.ts" --bundle --format=esm --platform=neutral --target=es2022 \
    "--external:npm:*" --log-level=warning \
    --banner:js="// $f — single-file build of supabase/functions/$f for pasting into the Supabase dashboard editor. Generated by scripts/build-dashboard-functions.sh; do not edit by hand." \
    --outfile="supabase/dashboard/$f.ts"
done
echo "Built supabase/dashboard/*.ts"
